#include <ctype.h>
#include <stdio.h>
#include <unistd.h>

char BSE(char rule[21]){
  char Sc = 0, Ec = 0;

  if (rule[0] != 'B'){ return 0; }
  for(int i = 0; i < 21; i++){
    if(rule[i] == 'S') {
      Sc++;
    }
    if(rule[i] == 'E') {
      Ec++;
    }
  }
  if (Sc != 1 || Ec != 1) return 0;
  return 1;
}

char NumberLength(char rule[21], short* B, short* S){
  (*B) = 0;
  (*S) = 0;
  int i = 1;
  while((*B) < 10){
    if(!isalpha(rule[i]) && !ispunct(rule[i])){ (*B)++; }
    else if (rule[i] == 'S'){ i++; break; }
    else{ return 0; }
    i++;
  }
  while((*S) < 10){
    if(!isalpha(rule[i]) && !ispunct(rule[i])){ (*S)++; }
    else if(rule[i] == 'E'){ break; }
    else{ return 0;}
    i++;
  }

  for (int i = 1; i < (*B) + 1; i++) {
    for (int j = 1; j < (*B) + 1; j++) {
      if(rule[i] == rule[j] && i != j){ return 0; }
    }
  }

  for (int i = (*B) + 2; i < ((*B) + 2) + (*S); i++) {
    for (int j = (*B) + 2; j < ((*B) + 2) + (*S); j++) {
      if(rule[i] == rule[j] && i != j){ return 0; }
    }
  }

  for (int i = 0; i < 21; i++) {
    if(rule[i] == '9'){ return 0; }
  }

  if((*S) >= 10 || (*B) >= 10){ return 0; }
  return 1;
}

/* The rule as a boolean function of 5 inputs: bit 0 = cell alive, bits 1-4 =
 * the neighbour count's bits (s0..s3). Counts 9-15 never happen, so those
 * inputs are don't-cares. Quine-McCluskey turns it into a short sum of
 * products that works on 64 cells at once. */
#define VARS 5
#define INPUTS (1 << VARS)

typedef struct { unsigned value, mask; } Implicant;  /* mask bit set = variable dropped */

static int Covers(Implicant t, unsigned m) { return (m & ~t.mask) == t.value; }
static int Literals(Implicant t) { return VARS - __builtin_popcount(t.mask); }

static int MinimizeRule(const char on[INPUTS], const char dontcare[INPUTS], Implicant* out) {
  Implicant cur[INPUTS * 8], next[INPUTS * 8], primes[INPUTS * 8];
  int n = 0, np = 0;
  for (unsigned m = 0; m < INPUTS; m++)
    if (on[m] || dontcare[m]) cur[n++] = (Implicant){ m, 0 };

  while (n > 0) {
    char used[INPUTS * 8] = { 0 };
    int nn = 0;
    for (int i = 0; i < n; i++)
      for (int j = i + 1; j < n; j++) {
        unsigned diff = cur[i].value ^ cur[j].value;
        if (cur[i].mask != cur[j].mask || __builtin_popcount(diff) != 1) continue;
        used[i] = used[j] = 1;
        Implicant t = { cur[i].value & ~diff, cur[i].mask | diff };
        int dup = 0;
        for (int k = 0; k < nn; k++) dup |= next[k].value == t.value && next[k].mask == t.mask;
        if (!dup) next[nn++] = t;
      }
    for (int i = 0; i < n; i++) if (!used[i]) primes[np++] = cur[i];
    for (int i = 0; i < nn; i++) cur[i] = next[i];
    n = nn;
  }

  /* Cover the on-set: essential primes first, then the prime covering the most
   * still-uncovered inputs (fewest literals on ties). */
  char covered[INPUTS] = { 0 }, picked[INPUTS * 8] = { 0 };
  int nout = 0;
  for (unsigned m = 0; m < INPUTS; m++) {
    if (!on[m] || covered[m]) continue;
    int only = -1, count = 0;
    for (int p = 0; p < np; p++) if (Covers(primes[p], m)) { only = p; count++; }
    if (count == 1 && !picked[only]) {
      picked[only] = 1;
      out[nout++] = primes[only];
      for (unsigned k = 0; k < INPUTS; k++) if (Covers(primes[only], k)) covered[k] = 1;
    }
  }
  for (;;) {
    int best = -1, best_gain = 0;
    for (int p = 0; p < np; p++) {
      if (picked[p]) continue;
      int gain = 0;
      for (unsigned m = 0; m < INPUTS; m++) gain += on[m] && !covered[m] && Covers(primes[p], m);
      if (gain > best_gain || (gain && gain == best_gain && Literals(primes[p]) < Literals(primes[best]))) {
        best = p;
        best_gain = gain;
      }
    }
    if (best < 0) break;
    picked[best] = 1;
    out[nout++] = primes[best];
    for (unsigned k = 0; k < INPUTS; k++) if (Covers(primes[best], k)) covered[k] = 1;
  }
  return nout;
}

static void WriteRuleBits(FILE* file, const char birth[9], const char survive[9]) {
  static const char* names[VARS] = { "alive", "s0", "s1", "s2", "s3" };
  char on[INPUTS] = { 0 }, dontcare[INPUTS] = { 0 };
  for (int count = 0; count < 16; count++)
    for (int alive = 0; alive <= 1; alive++) {
      int m = (count << 1) | alive;
      if (count > 8) dontcare[m] = 1;
      else on[m] = alive ? survive[count] : birth[count];
    }

  Implicant terms[INPUTS * 8];
  int n = MinimizeRule(on, dontcare, terms);

  fprintf(file, "/* Next state of 64 cells at once. s0..s3 are the bits of each cell's\n");
  fprintf(file, " * neighbour count, alive is the current state. Generated by BSGenerator. */\n");
  fprintf(file, "static inline uint64_t RuleBits(uint64_t s0, uint64_t s1, uint64_t s2, uint64_t s3, uint64_t alive) {\n");
  fprintf(file, "  (void)s0; (void)s1; (void)s2; (void)s3; (void)alive;\n");
  fprintf(file, "  return ");
  if (n == 0) fprintf(file, "0");
  for (int t = 0; t < n; t++) {
    if (t) fprintf(file, "\n       | ");
    if (Literals(terms[t]) == 0) { fprintf(file, "~0ULL"); continue; }
    fprintf(file, "(");
    int first = 1;
    for (int v = VARS - 1; v >= 0; v--) {
      if (terms[t].mask >> v & 1) continue;
      fprintf(file, "%s%s%s", first ? "" : " & ", (terms[t].value >> v & 1) ? "" : "~", names[v]);
      first = 0;
    }
    fprintf(file, ")");
  }
  fprintf(file, ";\n}\n");
}

int main(){
  char rule[21];
  short B = 0, S = 0;

  while(1){
    printf("Please input the ruleset for the game\n");
    scanf("%s21[^\n]", rule);
    scanf("%*c");
    if(BSE(rule)){
      if(NumberLength(rule, &B, &S)){
        break;
      }else{
        printf("Please enter a valid rule!\n");
        continue;
      }
    } else{
      printf("Please enter a valid rule!\n");
      continue;
    }
  }

  if (access("ruleset.c", F_OK) == 0) {
    remove("ruleset.c");
  }
  if (access("ruleset.h", F_OK) == 0) {
    remove("ruleset.h");
  }

  char birth[9] = { 0 }, survive[9] = { 0 };
  for (int i = 0; i < B; i++) birth[rule[i + 1] - '0'] = 1;
  for (int i = B + 2; i < (B + 2) + S; i++) survive[rule[i] - '0'] = 1;

  FILE* file;
  file = fopen("ruleset.h", "w");
  fprintf(file, "#pragma once\n\n");
  fprintf(file, "#include <stdint.h>\n\n");
  fprintf(file, "char RuleStateManager(char state, char cState);\n\n");
  WriteRuleBits(file, birth, survive);
  fclose(file);

  short number = 0;
  file = fopen("ruleset.c", "w");
  fprintf(file, "#include \"ruleset.h\"\n\n");
  fprintf(file, "char RuleStateManager(char state, char cState) {\n");
  fprintf(file, "  if (cState == 0) {\n");
  fprintf(file, "    switch (state){\n");

  for (int i = 0; i < B; i++) {
    number = rule[i+1] - 48;
    fprintf(file, "      case %d:\n        return 1;\n", number);
  }

  fprintf(file, "      default:\n        return 0;\n");
  fprintf(file, "    }\n  } else {\n");
  fprintf(file, "    switch (state){\n");

  for (int i = B + 2; i < (B + 2) + S; i++) {
    number = rule[i] - 48;
    fprintf(file, "      case %d:\n        return 1;\n", number);
  }

  fprintf(file, "      default:\n        return 0;\n");
  fprintf(file, "    }\n  }\n}");
  fclose(file);
}
